def sic_to_sector(sic: str | int | None) -> str | None:
    """SIC → 섹터. 모르면 None(비영업 9995 등 — 미분류로 남긴다)."""
    try:
        code = int(str(sic).strip())
    except (TypeError, ValueError):
        return None
    for lo, hi, sector in _RANGES:
        if lo <= code <= hi:
            return sector
    return None
