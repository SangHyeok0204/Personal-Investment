"""이 계좌를 **언제부터, 무엇을 자산으로 보고** 볼 것인가.

한 곳에만 둔다. 화면마다 따로 정하면 같은 계좌를 놓고 화면들이 다른 기간·다른
자산을 말하게 된다.

★2026-09-22 사용자 지정:
  · 투자 기간은 **2026-06-04 부터**.
  · 자산은 **예수금을 포함**한다(주식 평가액 + 예수금).

⚠️시작일을 바꿔도 **순입금이 0이 되지는 않는다.** 실측(2026-09-22): 6/4 이후에도
  입출금이 6건 있다 — 7/10 +2,546,942 · 7/12 +3,430 · 7/13 −2,022,016 ·
  7/21 +1,405,899 · 7/27 +189,739 · 7/28 −249,118 = **순 +1,874,876**.
  화면이 0 이라고 말하게 만들지 않는다. 이 흐름들이 새 자금이 아니라 계좌 간
  이동이라면 그때 따로 걸러야 하고, 지금은 그렇게 볼 근거가 없다.

⚠️시작일을 **모든** 화면에 강제하지 않는다:
  · 세금 — 양도소득세는 **역년(1/1~12/31)** 단위다. 투자 기간으로 자르면
    신고 단위가 깨진다.
  · 공시·뉴스·시장 — 내 계좌 기간과 무관하다.
"""
from __future__ import annotations

from datetime import date

#: 이 계좌를 보기 시작하는 날. 이 앞의 기록은 화면에서 다루지 않는다.
INVESTMENT_START = date(2026, 6, 4)

#: 자산 정의에 예수금을 포함하는가. 포함하면 비중의 분모도 총자산이 된다.
CASH_IN_ASSETS = True

ASSET_BASIS_NOTE = (
    "자산은 **주식 평가액 + 예수금**입니다. 비중의 분모도 같은 총자산이라,"
    " 예수금이 많으면 종목 비중이 그만큼 낮게 나옵니다."
)

START_NOTE = (
    f"투자 기간을 **{INVESTMENT_START.isoformat()}부터**로 봅니다."
    " 그 앞의 입출금·손익은 이 화면들에서 다루지 않습니다."
)


def since(days: int | None = None, today: date | None = None) -> date:
    """조회 하한. 요청한 기간이 더 짧으면 그쪽을 쓴다.

    ⚠️시작일보다 **앞으로는 내려가지 않는다.** 화면에서 '전체'를 눌러도
      투자 기간 밖을 끌어오지 않는다.
    """
    if days is None:
        return INVESTMENT_START
    today = today or date.today()
    from datetime import timedelta

    asked = today - timedelta(days=days)
    return max(asked, INVESTMENT_START)
